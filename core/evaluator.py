CLAUDE_CODE_NOTE = """

═══════════════════════════════════════════
КОНТЕКСТ ДЖЕРЕЛА: CLAUDE CODE
═══════════════════════════════════════════
Діалоги взято з Claude Code — агентного інструмента для роботи з кодом у терміналі.
Окрім [КОРИСТУВАЧ] і [ШІ] ти бачиш [ДІЇ ШІ] (які інструменти ШІ викликав: Read, Edit, Bash тощо)
та мітку [ПЕРЕРВАНО КОРИСТУВАЧЕМ] (користувач зупинив або відхилив дію ШІ).
Мітка «сесія S1, S2…» показує, до якої сесії належить діалог.
Критерії ті самі — 4D; ось як їх читати в цьому контексті:
• Delegation: ШІ тут працює переважно в режимі Агентності/Доповнення. Дивись, чи ставить
  користувач чітку мету, розбиває велике завдання на частини, чи залишає за собою рішення
  (архітектура, ревʼю), чи віддає ШІ завдання, що потребують його власної експертизи.
• Description: короткі промпти нормальні, якщо контекст лежить у репозиторії. Оцінюй ясність
  мети, обмежень, критеріїв «готово», посилань на конкретні файли/поведінку.
• Discernment: сильні сигнали — користувач виправляє ШІ, ставить уточнювальні питання,
  просить запустити тести/перевірити результат, перериває хибні дії ([ПЕРЕРВАНО КОРИСТУВАЧЕМ]),
  помічає помилки. Слабкий сигнал — прийняття всього підряд без перевірки.
• Diligence: секрети/ключі/персональні дані у промптах, перевірка перед комітом/деплоєм,
  відповідальність за наслідки дій ШІ у файловій системі та репозиторії.
Не оцінюй якість самого коду — оцінюй, як людина працює з ШІ."""


def evaluate(conversation_text: str, api_key: str, source: str = "") -> dict:
    """Run 4D evaluation on formatted conversation text. Returns parsed result dict."""
    client = anthropic.Anthropic(api_key=api_key)

    system = SYSTEM_PROMPT + REDACTION_NOTE
    if source == "Claude Code":
        system += CLAUDE_CODE_NOTE

    message = client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=4096,
        system=system,
        messages=[
            {
                "role": "user",
                "content": f"Ось архів діалогів користувача зі штучним інтелектом для аналізу:\n\n{conversation_text}\n\nПроведи 4D аналіз і поверни JSON.",
            }
        ],
    )

    raw = message.content[0].text.strip()

    # Strip markdown code fences if present
    if raw.startswith("```"):
        raw = raw.split("```")[1]
        if raw.startswith("json"):
            raw = raw[4:]
        raw = raw.strip()

    return json.loads(raw)
